def test_handoff_brief_is_written_as_lf_on_every_host(monkeypatch, tmp_path):
    session = importlib.import_module("scripts.session")
    path = tmp_path / "brief.md"
    path.write_bytes(b"# Brief\r\n\r\nExisting material\r\n")
