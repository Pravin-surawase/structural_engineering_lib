sys.path.insert(0, str(SCRIPTS))
preflight = importlib.import_module("preflight")


@pytest.fixture
def ready(monkeypatch):
    # The semantic state itself is owned/tested by git_state.py. This fixture
    # exercises the startup consumer, including failed query propagation.
    state = SimpleNamespace(
        ready_local=True,
        derived_action="READY_LOCAL",
        to_dict=lambda: {"derived_action": "READY_LOCAL"},
    )
    monkeypatch.setattr(preflight, "collect_repository_state", lambda *_a, **_k: state)
    monkeypatch.setattr(
        preflight, "python_binding", lambda: {"status": "PASS", "source_bound": True}
    )
    monkeypatch.setattr(preflight, "hook_readiness", lambda: {"status": "PASS"})
    return state


