def test_standard_hook_with_space_path_and_live_interpreter(monkeypatch, tmp_path):
    hook = tmp_path / "hook dir/pre-commit"
    hook.parent.mkdir()
    hook.write_text(
        "#!/bin/sh\n# File generated by pre-commit: https://pre-commit.com\nINSTALL_PYTHON="
        + shlex.quote(sys.executable)
        + "\nARGS=(hook-impl)\n",
        encoding="utf-8",
    )
    hook.chmod(0o755)
    calls = []

    def query(cmd):
        calls.append(cmd)
        return (0, str(hook)) if cmd[0] == "git" else (0, "")

    monkeypatch.setattr(preflight, "_run", query)
    assert preflight.hook_readiness()["status"] == "PASS"
    assert calls[-1] == [sys.executable, "-c", "import pre_commit"]
    # We never execute the hook or mutate its contents during a diagnostic.
    assert len(calls) == 4


def test_custom_hook_is_preserved_and_not_executed(monkeypatch, tmp_path):
    hook = tmp_path / "pre-commit"
    content = "#!/bin/sh\necho custom owner hook\n"
    hook.write_text(content, encoding="utf-8")
    monkeypatch.setattr(preflight, "_run", lambda _cmd: (0, str(hook)))
    assert preflight.hook_readiness()["status"] == "FAIL"
    assert hook.read_text(encoding="utf-8") == content


def test_shell_launch_failure_is_structured_not_unhandled(monkeypatch):
    def fail(*_args, **_kwargs):
        raise OSError("not a native executable")

    monkeypatch.setattr(preflight.subprocess, "run", fail)
    code, error = preflight._run(["missing-executable"])
    assert code == 1 and "not a native executable" in error


